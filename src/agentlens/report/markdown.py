"""The Markdown report (FR-C3): GitHub-flavoured, compact, made for a PR comment.

:class:`MarkdownRenderer` is registered as the ``markdown`` format, so
``render(report, "markdown")`` (or ``agentlens report X --format markdown``)
returns it. A comparison reads top to bottom as::

    <!-- agentlens-report -->
    ### ❌ AgentLens: gates failed · 3 metrics regressed
    <candidate> vs <baseline> · suite · cases
    | Metric | Baseline | Candidate | Δ | Δ% | 95% CI | Status |   (every metric)
    #### Gates (PASS/FAIL/SKIP per bound, then the notes)
    <details> case regressions / improvements </details>
    footer: experiment ids, git shas, bootstrap method

The first line is a hidden HTML comment, the **marker**: a bot looks for the
comment containing it and edits that one instead of posting a new comment on
every push (see :mod:`agentlens.integrations.github`). Give each report its
own key (``MarkdownRenderer(marker="agentlens-report:support")``) when a PR
gets several.

Status is never carried by an emoji alone: ✅/❌ come with a word
(``regression``, ``passed``) for screen readers and plain-text notifications.
Text that comes from users (case ids, reasons) is escaped so it cannot break
a table or inject HTML.
"""

from __future__ import annotations

import re

from agentlens.compare.gates import GateReport, GateResult
from agentlens.compare.model import CaseComparison, Direction, MetricDelta, Status
from agentlens.report.model import ComparisonReport, ExperimentReport
from agentlens.report.plain import MISSING, fmt_value
from agentlens.report.terminal import _bound, _metric_label
from agentlens.schema import Experiment

__all__ = [
    "DEFAULT_MARKER",
    "DEFAULT_MAX_CASES",
    "MarkdownRenderer",
    "marker_comment",
]

DEFAULT_MARKER = "agentlens-report"
"""Key of the hidden marker: the report starts with ``<!-- agentlens-report -->``."""

DEFAULT_MAX_CASES = 50
"""Rows per case table; the rest is summarised (a GitHub comment holds 65 536 characters)."""

PROJECT_URL = "https://github.com/ggbifulco/agentlens"

PASS = "✅"
FAIL = "❌"

_MARKER_KEY = re.compile(r"^[A-Za-z0-9_.:/@+=-]+$")
_STATUS_CELL = {
    Status.REGRESSION: f"{FAIL} **regression**",
    Status.IMPROVEMENT: f"{PASS} improvement",
    Status.UNCHANGED: "unchanged",
    Status.NO_DATA: "no data",
}
_ESCAPES = str.maketrans(
    {
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        "|": "\\|",
        "\\": "\\\\",
        "*": "\\*",
        "`": "\\`",
        "[": "\\[",
        "]": "\\]",
        "\n": " ",
        "\r": " ",
    }
)


def marker_comment(key: str = DEFAULT_MARKER) -> str:
    """The hidden HTML comment ``<!-- key -->`` that identifies a report.

    Raises:
        ValueError: if ``key`` is empty or has characters other than letters,
            digits and ``_ . : / @ + = -`` (so it cannot close the comment).
    """
    if not _MARKER_KEY.match(key):
        raise ValueError(
            f"invalid marker {key!r}: use letters, digits and _ . : / @ + = - (no spaces)"
        )
    return f"<!-- {key} -->"


def _esc(text: str) -> str:
    """``text`` safe inside a Markdown table cell (no HTML, no formatting, no ``|``)."""
    return text.translate(_ESCAPES)


def _code(text: str) -> str:
    """``text`` as inline code (a table-safe one: GitHub reads ``\\|`` as ``|`` in code too)."""
    clean = text.replace("`", "'").replace("\n", " ").replace("|", "\\|")
    return f"`{clean}`"


def _row(cells: list[str]) -> str:
    return "| " + " | ".join(cells) + " |"


def _table(headers: list[str], align: str, rows: list[list[str]]) -> list[str]:
    """A GFM table; ``align`` has one letter per column: ``l`` left, ``r`` right."""
    rule = ["---:" if a == "r" else "---" for a in align]
    return [_row(headers), _row(rule), *(_row(row) for row in rows)]


def _pct(value: float) -> str:
    return f"{value:.0%}"


def _plural(n: int, word: str) -> str:
    return f"{n} {word}{'' if n == 1 else 's'}"


def _git(experiment: Experiment) -> str | None:
    sha = experiment.config.get("git_sha")
    if not isinstance(sha, str):
        return None
    return _code(sha[:12]) + (" (dirty)" if experiment.config.get("git_dirty") else "")


def _footer_experiment(role: str, experiment: Experiment | None) -> str:
    if experiment is None:
        return f"{role}: in memory"
    parts = [f"{role} {_code(experiment.name)} ({_code(experiment.id)})"]
    git = _git(experiment)
    if git:
        parts.append(f"git {git}")
    return " ".join(parts)


def _footer(parts: list[str]) -> list[str]:
    credit = f"generated by [AgentLens]({PROJECT_URL})"
    return ["", "<sub>" + " · ".join([*parts, credit]) + "</sub>"]


# -- gates ---------------------------------------------------------------------------


def _gate_row(result: GateResult) -> list[str]:
    if result.skipped:
        verdict = "skip"
    elif result.passed:
        verdict = f"{PASS} pass"
    else:
        verdict = f"{FAIL} **fail**"
    actual = MISSING if result.actual is None else _bound(result.rule, result.actual)
    return [
        verdict,
        _esc(result.name),
        f"{result.rule} {_bound(result.rule, result.threshold)}",
        actual,
        _esc(result.reason),
    ]


def _gates_section(gates: GateReport) -> list[str]:
    n_skipped, n_failed = len(gates.skipped), len(gates.failures)
    n_passed = len(gates.results) - n_skipped - n_failed
    verdict = f"{PASS} passed" if gates.passed else f"{FAIL} failed"
    counts = f"{n_passed} passed, {n_failed} failed, {n_skipped} skipped"
    lines = ["", f"#### Gates: {verdict} ({counts})"]
    if gates.results:
        lines.append("")
        lines += _table(
            ["", "Gate", "Rule", "Actual", "Reason"],
            "lllrl",
            [_gate_row(result) for result in gates.results],
        )
    if gates.notes:
        lines.append("")
        lines += [f"> - {_esc(note)}" for note in gates.notes]
    return lines


# -- comparison ----------------------------------------------------------------------


def _delta(metric: MetricDelta) -> str:
    return fmt_value(metric.delta, signed=True)


def _delta_pct(metric: MetricDelta) -> str:
    return MISSING if metric.delta_pct is None else f"{metric.delta_pct:+.1f}%"


def _interval(metric: MetricDelta) -> str:
    if metric.ci_low is None or metric.ci_high is None:
        return MISSING
    return f"[{fmt_value(metric.ci_low, signed=True)}, {fmt_value(metric.ci_high, signed=True)}]"


def _metric_row(metric: MetricDelta) -> list[str]:
    better = "↑" if metric.direction is Direction.HIGHER_IS_BETTER else "↓"
    name = _esc(_metric_label(metric.name))
    if metric.status is Status.REGRESSION:
        name = f"**{name}**"
    return [
        f"{name} {better}",
        fmt_value(metric.baseline),
        fmt_value(metric.candidate),
        _delta(metric),
        _delta_pct(metric),
        _interval(metric),
        _STATUS_CELL[metric.status],
    ]


def _comparison_headline(report: ComparisonReport) -> str:
    cmp, gates = report.comparison, report.gates
    findings: list[str] = []
    if cmp.regressions:
        findings.append(f"{_plural(len(cmp.regressions), 'metric')} regressed")
    if cmp.improvements:
        findings.append(f"{len(cmp.improvements)} improved")
    if cmp.case_regressions:
        findings.append(f"{_plural(len(cmp.case_regressions), 'case')} regressed")
    if not findings:
        findings.append("no metric changed" if cmp.metrics else "nothing to compare")
    if gates is not None:
        ok = gates.passed
        findings.insert(0, "gates passed" if ok else "gates failed")
    else:
        ok = not cmp.regressions
    return f"### {PASS if ok else FAIL} AgentLens: {' · '.join(findings)}"


def _cases_details(
    title: str, cases: list[CaseComparison], *, max_cases: int, open_: bool
) -> list[str]:
    rows = [
        [
            _code(case.case_id),
            f"{fmt_value(case.pass_rate.baseline)} → {fmt_value(case.pass_rate.candidate)}",
            f"{case.baseline_runs}/{case.candidate_runs}",
            ", ".join(_esc(name) for name in case.regressed_evaluators),
        ]
        for case in cases[:max_cases]
    ]
    lines = [
        "",
        f"<details{' open' if open_ else ''}><summary>{title} ({len(cases)})</summary>",
        "",
        *_table(["Case", "Pass rate", "Runs (base/cand)", "Regressed evaluators"], "lrrl", rows),
    ]
    if len(cases) > max_cases:
        lines += ["", f"…and {len(cases) - max_cases} more."]
    return [*lines, "", "</details>"]


def _id_list(ids: list[str], max_cases: int) -> str:
    shown = ", ".join(_code(case_id) for case_id in ids[:max_cases])
    more = f" …and {len(ids) - max_cases} more" if len(ids) > max_cases else ""
    return shown + more


# -- experiment ----------------------------------------------------------------------


def _experiment_headline(report: ExperimentReport) -> str:
    gates = report.gates
    ok = gates.passed if gates is not None else report.passed == report.runs
    runs = f"{report.passed}/{report.runs} runs passed"
    if report.runs:
        runs += f" ({_pct(report.pass_rate)})"
    findings = [runs]
    if report.errors:
        findings.append(_plural(report.errors, "error"))
    if gates is not None:
        findings.insert(0, "gates passed" if gates.passed else "gates failed")
    return f"### {PASS if ok else FAIL} AgentLens: {' · '.join(findings)}"


def _experiment_metric(name: str, value: float) -> list[str]:
    return [_esc(_metric_label(name)), _pct(value) if name == "pass_rate" else fmt_value(value)]


# -- renderer ------------------------------------------------------------------------


class MarkdownRenderer:
    """GitHub-flavoured Markdown reports, compact enough for a PR comment.

    Args:
        marker: Key of the hidden ``<!-- key -->`` first line that lets a bot
            find and update its comment; ``None`` for no marker.
        max_cases: Rows per case table before the rest is summarised.

    Raises:
        ValueError: for an invalid ``marker`` (see :func:`marker_comment`) or
            ``max_cases < 1``.
    """

    def __init__(
        self, *, marker: str | None = DEFAULT_MARKER, max_cases: int = DEFAULT_MAX_CASES
    ) -> None:
        if max_cases < 1:
            raise ValueError(f"max_cases must be >= 1, got {max_cases}")
        self.marker = marker
        self._marker_line = [marker_comment(marker)] if marker is not None else []
        self.max_cases = max_cases

    def comparison(self, report: ComparisonReport) -> str:
        """Verdict, metrics table, gates, case changes (collapsed) and footer."""
        cmp = report.comparison
        cases = _plural(len(cmp.cases), "paired case")
        unpaired = [
            f"{len(ids)} {label}"
            for label, ids in (("added", cmp.added_cases), ("removed", cmp.removed_cases))
            if ids
        ]
        if unpaired:
            cases += f" ({', '.join(unpaired)})"
        context = [
            f"**{_esc(cmp.candidate.name)}**" if cmp.candidate else "**candidate**",
            "vs",
            f"**{_esc(cmp.baseline.name)}**" if cmp.baseline else "**baseline**",
        ]
        side = cmp.candidate or cmp.baseline
        suite = side.suite if side is not None else None
        details = [" ".join(context), *([f"suite {_code(suite)}"] if suite else []), cases]
        lines = [*self._marker_line, _comparison_headline(report), "", " · ".join(details)]

        level = f"{cmp.confidence:.0%}"
        if cmp.metrics:
            lines.append("")
            lines += _table(
                ["Metric", "Baseline", "Candidate", "Δ", "Δ%", f"{level} CI", "Status"],
                "lrrrrrl",
                [_metric_row(metric) for metric in cmp.metrics],
            )
            lines += [
                "",
                f"<sub>↑ higher is better, ↓ lower is better; a metric changed when its "
                f"{level} CI excludes 0.</sub>",
            ]
        if report.gates is not None:
            lines += _gates_section(report.gates)
        if cmp.case_regressions:
            lines += _cases_details(
                "Case regressions", cmp.case_regressions, max_cases=self.max_cases, open_=False
            )
        if cmp.case_improvements:
            lines += _cases_details(
                "Case improvements", cmp.case_improvements, max_cases=self.max_cases, open_=False
            )
        for label, ids in (("Added cases", cmp.added_cases), ("Removed cases", cmp.removed_cases)):
            if ids:
                lines += ["", f"**{label}** ({len(ids)}): {_id_list(ids, self.max_cases)}"]
        method = f"paired bootstrap, {cmp.resamples} resamples, {level} CI"
        if cmp.seed is not None:
            method += f", seed {cmp.seed}"
        lines += _footer(
            [
                _footer_experiment("baseline", cmp.baseline),
                _footer_experiment("candidate", cmp.candidate),
                method,
            ]
        )
        return "\n".join(lines)

    def experiment(self, report: ExperimentReport) -> str:
        """Verdict, metrics, gates, failing cases (collapsed) and footer."""
        exp = report.experiment
        context = [f"**{_esc(exp.name)}**", f"suite {_code(exp.suite)}"]
        model = exp.config.get("model")
        if isinstance(model, str):
            context.append(f"model {_code(model)}")
        context.append(_plural(len(report.cases), "case"))
        lines = [*self._marker_line, _experiment_headline(report), "", " · ".join(context)]
        if report.metrics:
            lines.append("")
            lines += _table(
                ["Metric", "Mean over cases"],
                "lr",
                [_experiment_metric(name, value) for name, value in report.metrics.items()],
            )
        if report.gates is not None:
            lines += _gates_section(report.gates)
        failing = [case for case in report.cases if case.passed < case.runs]
        if failing:
            rows = [
                [
                    _code(case.case_id),
                    f"{case.passed}/{case.runs}",
                    str(case.errors) if case.errors else "",
                    ", ".join(_esc(name) for name in case.failed_evaluators),
                ]
                for case in failing[: self.max_cases]
            ]
            lines += [
                "",
                f"<details><summary>Failing cases ({len(failing)} of {len(report.cases)})"
                "</summary>",
                "",
                *_table(["Case", "Passed", "Errors", "Failed evaluators"], "lrrl", rows),
            ]
            if len(failing) > self.max_cases:
                lines += ["", f"…and {len(failing) - self.max_cases} more."]
            lines += ["", "</details>"]
        lines += _footer([_footer_experiment("experiment", exp)])
        return "\n".join(lines)
